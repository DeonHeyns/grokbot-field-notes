#!/usr/bin/env python3
"""Build complete ChatGPT prompts and Cursor rules from reviewed role cards."""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = (
    "Owns", "Does not own", "Source of truth", "Needs approval for",
    "Triggers", "Outputs", "Role description",
)


def parse_role(text, source):
    title = re.match(r"# ([^\n]+)\n", text)
    category = re.search(r"^\*\*Category:\*\* ([^\n]+)\n\n([^\n]+)", text, re.M)
    if not title or not category:
        raise ValueError(f"{source}: missing title, category or summary")
    sections = {}
    # Ignore headings within fenced examples when locating section boundaries.
    active = None
    fence = None
    for line in text.splitlines():
        if line.startswith("```"):
            fence = None if fence else "```"
        if not fence and line.startswith("## "):
            active = line[3:]
            if active in sections:
                raise ValueError(f"{source}: duplicate section {active}")
            sections[active] = []
        elif active:
            sections[active].append(line)
    if fence:
        raise ValueError(f"{source}: unclosed code fence")
    sections = {k: "\n".join(v).strip() for k, v in sections.items()}
    for name in REQUIRED:
        if not sections.get(name):
            raise ValueError(f"{source}: missing or empty section {name}")
    prompt = re.fullmatch(r"```text\n(.+?)\n```", sections["Role description"], re.S)
    if not prompt or not prompt.group(1).strip():
        raise ValueError(f"{source}: expected one nonempty text prompt block")
    return {
        "title": title.group(1), "category": category.group(1),
        "summary": category.group(2), "sections": sections,
        "prompt": prompt.group(1),
    }


def instruction_body(role, base):
    parts = [base.strip(), "# Role assignment", role["prompt"]]
    for name in REQUIRED[:-1] + ("Routines",):
        if name in role["sections"]:
            parts.append(f"## {name}\n\n{role['sections'][name]}")
    return "\n\n".join(parts) + "\n"


def expected_outputs(root, target="all"):
    base = (root / "ports/chatgpt/BASE.md").read_text(encoding="utf-8")
    if not base.strip():
        raise ValueError("Shared operating instructions cannot be empty")
    outputs = {}
    sources = sorted(p for p in (root / "roster").glob("*.md") if p.name != "README.md")
    if not sources:
        raise ValueError("No role cards found")
    for src in sources:
        role = parse_role(src.read_text(encoding="utf-8"), src.name)
        body = instruction_body(role, base)
        if target in ("all", "chatgpt"):
            outputs[root / "ports/chatgpt/roles" / src.name] = (
                f"# {role['title']}\n\n{role['summary']}\n\n"
                f"Source: [role card](../../../roster/{src.name}). "
                "[Setup](../README.md).\n\n"
                "Copy the complete block below. Replace placeholders and remove unused\n"
                "options before running. Nothing is connected or scheduled by this file.\n\n"
                f"````text\n{body}````\n\n"
                "<!-- Generated by scripts/build_ports.py; edit the role card or BASE.md. -->\n"
            )
        if target in ("all", "cursor"):
            description = json.dumps(role["title"] + ". " + role["summary"], ensure_ascii=False)
            outputs[root / "ports/cursor/rules" / f"{src.stem}.mdc"] = (
                f"---\ndescription: {description}\nalwaysApply: false\n---\n\n"
                f"{body}\n<!-- Generated from roster/{src.name} and ports/chatgpt/BASE.md. "
                "Run scripts/build_ports.py. -->\n"
            )
    return outputs


def stale_paths(root, outputs, target):
    patterns = []
    if target in ("all", "chatgpt"):
        patterns.append((root / "ports/chatgpt/roles", "*.md"))
    if target in ("all", "cursor"):
        patterns.append((root / "ports/cursor/rules", "*.mdc"))
    return sorted(p for folder, pattern in patterns for p in folder.glob(pattern) if p not in outputs)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on drift without writing files")
    parser.add_argument("--target", choices=("all", "chatgpt", "cursor"), default="all")
    args = parser.parse_args(argv)
    try:
        outputs = expected_outputs(ROOT, args.target)
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    stale = stale_paths(ROOT, outputs, args.target)
    drift = [p for p, content in outputs.items()
             if not p.exists() or p.read_text(encoding="utf-8") != content]
    if args.check:
        if stale or drift:
            for p in stale:
                print(f"Unexpected generated file: {p.relative_to(ROOT)}")
            for p in drift:
                print(f"Missing or outdated: {p.relative_to(ROOT)}")
            return 1
        print(f"Verified {len(outputs)} generated role files")
        return 0
    # A removed role can leave manually edited files behind. Do not delete blindly.
    if stale:
        for p in stale:
            print(f"Review and remove obsolete generated file: {p.relative_to(ROOT)}")
        return 1
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"Wrote {len(outputs)} generated role files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
